#!/usr/bin/env python3
"""Renders RESULTS.md from results/ (revision 2; no number is typed by hand). The paper's numbers come from the same
files through make_numbers.py."""
import json, os

R = os.path.join(os.path.dirname(os.path.abspath(__file__)), "results")
J = lambda f: json.load(open(os.path.join(R, f)))
L, F = J("v2_summary.json"), J("free_summary.json")
TL, TF = L["totals"], F["totals"]
A = J("agreement.json"); OL, OF = J("oracle2_lexical.json"), J("oracle2_label_free.json")
RB, TM, OV = J("robustness.json"), J("v2_timing.json"), J("proto_overhead.json")
CP, TX = J("checker_probes.json"), J("taxonomy.json")
pct = lambda a, b: f"{100 * a / b:.1f}%"

out = ["# SchemaCaps — pilot results (generated by report2.py)", "",
       "| Stratum | Pairs | Changed | Compatible | CA core (lex.) | CA strict (lex.) | CA label-free | Pin | Compat | SC lexical | SC label-free |",
       "|---|---|---|---|---|---|---|---|---|---|---|"]
for name, l, f in (("A", L["per_strate"]["A"], F["per_strate"]["A"]), ("B", L["per_strate"]["B"], F["per_strate"]["B"]),
                   ("Total", TL, TF)):
    out.append(f"| {name} | {l['pairs']} | {l['schema_changed']} | {l['compatible']} | {l['ca_core']} | {l['ca_strict']} | "
               f"{f['ca_strict']} | {l['def_changed']} | {l['rq_compat']} | {l['rq_strict']} | {f['rq_strict']} |")
out += ["",
        f"- Compatible changes that widen some coordinate (label-free): {TF['ca_strict']} of {TF['compatible']} "
        f"({pct(TF['ca_strict'], TF['compatible'])}); widening a lexically authority-bearing argument (core): {TL['ca_core']} "
        f"({pct(TL['ca_core'], TL['compatible'])}); package bootstrap interval "
        f"[{100 * RB['bootstrap_interval_95'][0]:.1f}, {100 * RB['bootstrap_interval_95'][1]:.1f}]%.",
        f"- Re-approvals on existing tools: pin {TL['def_changed']}, compatibility {TL['rq_compat']}, SchemaCaps label-free "
        f"{TF['rq_strict']}, SchemaCaps lexical {TL['rq_strict']}; plus {TL['added']} added tools for every rule. "
        f"Undecided: {TF['undecided']} (label-free), {TL['undecided']} (lexical).",
        f"- Taxonomy (compatible changes, lexical / label-free): field added on closed object {TX['lexical']['new_authority_arg']} / "
        f"{TX['label_free']['new_authority_arg']}; domain widened {TX['lexical']['widened']} / {TX['label_free']['widened']}; "
        f"object opened {TX['lexical']['object_opened']} / {TX['label_free']['object_opened']}; strict narrowings (all changes) "
        f"{TX['strict_narrowings_all_changes']}.",
        f"- Annotation ({A['n']} cases, {A['flagged']} flagged + {A['unflagged']} unflagged): raw agreement "
        f"{100 * A['percent_agreement']:.1f}%, Cohen's kappa {A['cohen_kappa']} ({A['cohen_kappa_unsure_as_no']} reading unsure as no); "
        f"{len(A['disagreements'])} disagreements adjudicated; lexical rule precision {A['lexical_rule_precision']}, recall "
        f"{A['lexical_rule_recall']} (upper bound); human-validated compatible core amplifications K = {A['K_final_core']}.",
        f"- Oracle, every silent re-bind: label-free {OF['schema_rebinds']} schema-changing re-binds, {OF['generated_checks']} "
        f"generated calls, {len(OF['unsound'])} counterexamples; lexical {OL['schema_rebinds']} re-binds, {len(OL['unsound'])} "
        f"counterexamples.",
        f"- Checker probes: raw jsonsubschema unsound on {len(CP['raw_unsound'])} of {CP['probes']}; guarded checker on "
        f"{len(CP['guarded_unsound'])}. Guard during classification: {TF['checker_guard'] if 'checker_guard' in TF else F.get('checker_guard')}.",
        f"- Decision on a changed tool (cold): label-free median {TM['label_free']['median_ms']} ms, p99 {TM['label_free']['p99_ms']} ms; "
        f"lexical median {TM['lexical']['median_ms']} ms. Proxy overhead: +{OV['added_call_ms']['median']} ms per call, "
        f"+{OV['added_list_ms']['median']} ms per list ({OV['runs']} runs x {OV['iterations_per_run']}).",
        ""]
open(os.path.join(os.path.dirname(R), "RESULTS.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
